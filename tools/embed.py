#!/usr/bin/env python3
"""Embed files into the firmware for the 'install' command.
usage: embed.py OUT.c  SDPATH=FILE ..."""
import sys
out = open(sys.argv[1], "w")
out.write("/* generated by tools/embed.py */\n#include \"shell.h\"\n\n")
names = []
for i, arg in enumerate(sys.argv[2:]):
    dst, src = arg.split("=", 1)
    data = open(src, "rb").read()
    out.write("static const unsigned char f%d[%d] = {\n" % (i, len(data) + 1))
    for j in range(0, len(data), 20):
        out.write("".join("%d," % b for b in data[j:j + 20]) + "\n")
    out.write("0};\n")
    names.append((dst, i, len(data)))
out.write("\nconst EmbeddedFile embedded_files[] = {\n")
for dst, i, n in names:
    out.write('    {"%s", f%d, %d},\n' % (dst, i, n))
out.write("    {0, 0, 0}\n};\nconst int embedded_count = %d;\n" % len(names))
